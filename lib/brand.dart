/// هوية النسخة الإقليمية من التطبيق.
///
/// كل فرع إقليمي يغيّر [slug] و[backendOrigin] هنا بس — لا نسخ للخادم ولا
/// تفريع لملفات الخدمات. الخادم ما بيقدر يعرف باسم مين يردّ ولا بأي لهجة إلا
/// إذا قال له العميل، وهذا شغل [slug].
///
/// الاسم المعروض واللهجة ما بيجوا من هنا: الخادم يملك خرائط slug ← (اسم،
/// لهجة) — انظر brands.ts — عشان إضافة نسخة جديدة ما تحتاج إصدار تطبيق جديد
/// للنسخ القديمة.
///
/// **مهم:** إذا ما انبعث هذا المعرّف، الخادم يفترض النسخة الافتراضية (ريكو،
/// لهجة سعودية) — فتدلل يصير يردّ بلهجة غير لهجته.
class Brand {
  const Brand._();

  /// المعرّف المبعوث مع كل نداء تصنيف/صياغة/تحويل صوتي.
  static const String slug = 'tadallal';

  /// أصل خدمات الخادم لهذي النسخة (بدون / في الآخر). كان مكرّراً بعشرة ملفات
  /// خدمة، فأي فرع إقليمي جديد كان لازم يلقاهم كلهم — وينسى واحد فيضل يكلّم
  /// خادم النسخة الثانية بهدوء.
  ///
  /// للتجربة المحلية بدّله لـ http://localhost:3000 (iOS Simulator/سطح
  /// المكتب) أو http://10.0.2.2:3000 (Android Emulator — localhost عنده يشير
  /// لجهاز المحاكي نفسه لا لجهازك).
  static const String backendOrigin = 'https://tadallal.onrender.com';
}
